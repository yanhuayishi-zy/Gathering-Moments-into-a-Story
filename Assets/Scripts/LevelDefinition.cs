        private static InvestigationStep I(string name, string observation, string correct, string wrongA,
            string wrongB, string discovery, int chain, int step)
        {
            return new InvestigationStep
            {
                Name = name,
                Observation = observation,
                CorrectAction = correct,
                WrongActionA = wrongA,
                WrongActionB = wrongB,
                Discovery = discovery,
                Chain = chain,
                Step = step
            };
        }

